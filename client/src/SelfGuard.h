//
//   1) **默认关闭**。只有 r6m.ini 里自保护=1 或环境变量 R6M_SELFPROTECT=1
//      才拉起常驻。理由：这类"杀不掉"的行为一旦默认开启，会在调试机/自己人
//      的机器上直接咬人 —— 本项目上一版会话锁定就是这样，最后只能进安全模式收场。
//
//   2) **有界复活**。同一窗口内被反复结束就认定是**管理员在手动关**，
//      常驻自行退出并撤掉自启。管理员必须永远保留停止它的能力；
//      无止境复活不是"防护"，是恶意软件行为。
//
//   3) **安全模式不复活**。那里是救援环境，常驻在里面复活等于兼容救援。
//
//   4) **不做"不可杀"**。不硬化进程 DACL、不设 critical process
//      （后者被杀会让整机 BSOD）。防护靠"回来"，不靠"杀不掉"。
//
// 撤销方式（三条任选，从轻到重）：
//   · 任务管理器结束主进程与常驻进程各 3 次以上（有界复活会自动放弃）
//   · 删掉 r6m.ini 里的自保护=1 后重启进程
//   · 安全模式启动（常驻在其中不复活），再清理自启项
// ═══════════════════════════════════════════════════════════════════════════

#pragma once

#include <string>

namespace r6m {

class SelfGuard {
public:
    // 主进程调用：按配置决定是否拉起常驻（幂等，重复调用安全）
    static void Init();

    // 命令行里是否带 --r6m-guard（常驻进程模式）
    static bool IsGuardianMode();

    // 常驻进程主循环，返回进程退出码
    static int RunGuardian();

    // 主进程正常退出时调用：告诉常驻"是我自己走的，别复活"
    // （被强杀时不会走到这里，常驻据此区分"优雅退出"与"被杀"）
    static void Shutdown();

    // 供诊断/日志：当前是否启用、为什么
    static std::string StatusLine();

    // 自自启动配置：启动时建/校正计划任务，以最高权限把自己拉起来（幂等；失败也如实返回）
    static bool EnsureSelfTask();
};

} // namespace r6m
